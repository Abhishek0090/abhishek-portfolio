import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { gunzipSync } from "node:zlib";

const args = process.argv.slice(2);
const force = args.includes("--force");
const pathArg = args.find((a) => !a.startsWith("--"));
let target = pathArg ? resolve(pathArg) : process.cwd();
if (
  !pathArg &&
  !existsSync(join(target, "package.json")) &&
  existsSync(join(target, "portfolio", "package.json"))
)
  target = join(target, "portfolio");

// Refuse to write over a different project by mistake.
const pkgPath = join(target, "package.json");
if (existsSync(pkgPath) && !force) {
  let name = "";
  try {
    name = JSON.parse(readFileSync(pkgPath, "utf8")).name;
  } catch {}
  if (name !== "portfolio") {
    console.error(
      'This folder has a package.json for "' +
        name +
        '", not the portfolio: ' +
        target,
    );
    console.error(
      "Run this in an empty folder or in the portfolio project, or add --force.",
    );
    process.exit(1);
  }
}
if (
  !existsSync(pkgPath) &&
  existsSync(target) &&
  readdirSync(target).some(
    (f) => !f.endsWith(".mjs") && !PROJECT_ENTRIES.has(f),
  ) &&
  !force
) {
  console.error(
    "The folder " + target + " is not empty and is not the portfolio project.",
  );
  console.error(
    "Use an empty folder, pass the project path as an argument, or add --force.",
  );
  process.exit(1);
}

let payload;
try {
  payload = JSON.parse(
    gunzipSync(Buffer.from(DATA.replace(/\s+/g, ""), "base64")).toString(
      "utf8",
    ),
  );
} catch {
  console.error(
    "This script is damaged (the paste was probably cut off or changed). Copy it again in full.",
  );
  process.exit(1);
}

console.log("Abhishek Pal - Portfolio - full setup\nFolder: " + target + "\n");
let written = 0,
  unchanged = 0;
for (const f of payload.files) {
  const dest = join(target, f.p);
  const data = Buffer.from(f.c, f.e);
  if (existsSync(dest) && readFileSync(dest).equals(data)) {
    unchanged++;
    continue;
  }
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, data);
  written++;
  console.log("  wrote  " + f.p);
}
const bad = payload.files.filter((f) => {
  const dest = join(target, f.p);
  return (
    !existsSync(dest) ||
    createHash("sha256").update(readFileSync(dest)).digest("hex") !== f.h
  );
});
console.log(
  "\nDone: " + written + " written, " + unchanged + " already up to date.",
);
if (bad.length) {
  console.error(
    "WARNING: these files did not verify: " + bad.map((f) => f.p).join(", "),
  );
  process.exit(1);
}
console.log("All " + payload.files.length + " files verified.");
const manifestPath = join(target, ".portfolio-files.json");
let known = [];
try {
  known = JSON.parse(readFileSync(manifestPath, "utf8"));
} catch {}
writeFileSync(
  manifestPath,
  JSON.stringify(
    [...new Set([...known, ...payload.files.map((f) => f.p)])].sort(),
    null,
    1,
  ) + "\n",
);
const [major, minor] = process.versions.node.split(".").map(Number);
if (major < 20 || (major === 20 && minor < 9))
  console.warn(
    "\nNote: the site needs Node.js 20.9+ to run. You have " +
      process.versions.node +
      ".",
  );
console.log(
  "\nNext:\n  1. npm ci\n  2. npm run dev   and open http://localhost:3000\n  3. Edit src/data/profile.ts to add your email and links",
);

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  rmdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { gunzipSync } from "node:zlib";

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const noInstall = args.includes("--no-install");
const keep = args.includes("--keep");
const pathArg = args.find((a) => !a.startsWith("--"));

const isProject = (dir) => {
  try {
    return (
      JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).name ===
        "portfolio" && existsSync(join(dir, "src"))
    );
  } catch {
    return false;
  }
};
let target = pathArg ? resolve(pathArg) : process.cwd();
if (!pathArg && !isProject(target) && isProject(join(target, "portfolio")))
  target = join(target, "portfolio");
if (!isProject(target)) {
  console.error("Could not find the portfolio project in: " + target);
  console.error(
    "Run this inside the project folder (the one with package.json and src), or pass its path.",
  );
  console.error("Setting up a new machine? Use portfolio-setup.mjs instead.");
  process.exit(1);
}

let payload;
try {
  payload = JSON.parse(
    gunzipSync(Buffer.from(DATA.replace(/\s+/g, ""), "base64")).toString(
      "utf8",
    ),
  );
} catch {
  console.error(
    "This script is damaged (the paste was probably cut off or changed). Copy it again in full.",
  );
  process.exit(1);
}

console.log(
  "Abhishek Pal - Portfolio - update" +
    (dryRun ? " (dry run, nothing is changed)" : "") +
    "\nProject: " +
    target +
    "\n",
);
const read = (p) =>
  existsSync(join(target, p)) ? readFileSync(join(target, p)) : null;
const before = { pkg: read("package.json"), lock: read("package-lock.json") };

let written = 0,
  unchanged = 0,
  removed = 0;
for (const f of payload.files) {
  const dest = join(target, f.p);
  const data = Buffer.from(f.c, f.e);
  if (existsSync(dest) && readFileSync(dest).equals(data)) {
    unchanged++;
    continue;
  }
  written++;
  console.log("  " + (existsSync(dest) ? "updated" : "added  ") + "  " + f.p);
  if (dryRun) continue;
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, data);
}

// Remove files an earlier version installed that this one no longer has. Only files listed in the manifest
// (or known obsolete files) are touched, so your own files and .env files are never deleted.
const manifestPath = join(target, ".portfolio-files.json");
let previous = [];
try {
  previous = JSON.parse(readFileSync(manifestPath, "utf8"));
} catch {}
const current = new Set(payload.files.map((f) => f.p));
if (!keep) {
  for (const p of [...new Set([...previous, ...[]])]) {
    if (current.has(p) || p.startsWith(".env")) continue;
    const dest = join(target, p);
    if (!existsSync(dest)) continue;
    removed++;
    console.log("  removed  " + p);
    if (dryRun) continue;
    rmSync(dest, { force: true });
    for (
      let dir = dirname(dest);
      dir.length > target.length;
      dir = dirname(dir)
    ) {
      try {
        if (readdirSync(dir).length) break;
        rmdirSync(dir);
      } catch {
        break;
      }
    }
  }
}

if (dryRun) {
  console.log(
    "\nDry run: " +
      written +
      " to write, " +
      removed +
      " to remove, " +
      unchanged +
      " already up to date.",
  );
  process.exit(0);
}
writeFileSync(
  manifestPath,
  JSON.stringify([...current].sort(), null, 1) + "\n",
);

const bad = payload.files.filter((f) => {
  const dest = join(target, f.p);
  return (
    !existsSync(dest) ||
    createHash("sha256").update(readFileSync(dest)).digest("hex") !== f.h
  );
});
console.log(
  "\nDone: " +
    written +
    " written, " +
    removed +
    " removed, " +
    unchanged +
    " already up to date.",
);
if (bad.length) {
  console.error(
    "WARNING: these files did not verify: " + bad.map((f) => f.p).join(", "),
  );
  process.exit(1);
}
console.log("All " + payload.files.length + " files verified.");

const depsChanged =
  !before.pkg?.equals(read("package.json")) ||
  !before.lock?.equals(read("package-lock.json"));
if ((depsChanged || !existsSync(join(target, "node_modules"))) && !noInstall) {
  console.log("\nPackages changed, running npm install...\n");
  const r = spawnSync("npm install --no-audit --no-fund", {
    cwd: target,
    stdio: "inherit",
    shell: true,
  });
  if (r.status !== 0) {
    console.error("\nnpm install failed. Run it yourself in " + target);
    process.exit(1);
  }
}
console.log("\nUpdated. Start it with:  npm run dev");
